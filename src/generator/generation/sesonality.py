"""Сезонность: суточная, недельная и годовая активность как чистые функции времени.

Интенсивность заказов строится из трех компонент:

    1. Суточный цикл: ночью заказов мало, днем их больше, во второй половине
    дня (после работы) наступает пик.
    2. Недельный цикл: в выходные покупают активнее, чем в будни.
    3. Годовой цикл: рост перед Новым годом, спад в летний сезон.

Каждая компонента возвращает безразмерный коэффициент активности около 1.0
(больше 1.0 - заказов больше обычного, меньше 1.0 - меньше обычного).
Итоговая сезонность - произведение трех коэффициентов; ее используют
генераторы, чтобы менять количество заказов и вероятности выбора товаров.

Все функции здесь - чистые: результат зависит только от переданного момента
времени и не зависит от случайности и внешнего состояния. Случайный шум
добавляется позже, в самплерах, поэтому сезонность легко проверять тестами
на фиксированных датах.
"""

import math
from datetime import datetime

DAILY_AMPLITUDE = 0.5
WEEKLY_AMPLITUDE = 0.15
YEARLY_AMPLITUDE = 0.20


def daily_factor(at: datetime) -> float:
    """Суточный множитель: пик в 17:00, минимум около 05:00.

    Меньше всего заказов ночью и ранним утром, больше - во второй половине дня.
    """
    hour = at.hour + at.minute / 60.0 + at.second / 3600.0
    return 1.0 + DAILY_AMPLITUDE * math.cos(2.0 * math.pi * (hour - 17.0) / 24.0)


def weekly_factor(at: datetime) -> float:
    """Недельный множитель: в выходные заказов больше, в середине недели меньше.
    
    Позиция внутри недели в днях: от 0.0 (пн 00:00) до 7.0 (следующий пн 00:00)
    """

    week_position = at.weekday() + (at.hour + at.minute / 60.0) / 24.0
    return 1.0 + WEEKLY_AMPLITUDE * math.cos(2.0 * math.pi * (week_position - 6.0) / 7.0)


def yearly_factor(at: datetime) -> float:
    """Годовой множитель: пик перед Новым годом, спад летом."""
    day_of_year = at.timetuple().tm_yday
    return 1.0 + YEARLY_AMPLITUDE * math.cos(2.0 * math.pi * (day_of_year - 350.0) / 365.0)


def activity_factor(at: datetime) -> float:
    """Итоговый множитель активности: произведение суточного, недельного и годового."""
    return daily_factor(at) * weekly_factor(at) * yearly_factor(at)